/** Typography and decoration spec for one heading level. */
internal data class HeadingSpec(
    val size: Float,
    val weight: FontWeight,
    val top: Int,
    val bottom: Int,
    val borderLeft: Boolean,
    val borderWidth: Dp,
    val borderBottom: Boolean,
    val muted: Boolean,
    val lineHeightMultiplier: Float,
)

