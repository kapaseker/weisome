 * GITHUB mirrors docs/theme/github/github.scss (primer/css src/markdown, light values resolved),
 * SMART_BLUE mirrors docs/theme/smart-blue/smart-blue.css (cumt-robin/juejin-markdown-theme-smart-blue@f740565).
